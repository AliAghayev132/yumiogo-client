/** Ionicons name ("people-outline") → lucide component, or null when there is no match. */
export const ionToLucide = (name) => {
  const base = String(name || '')
    .trim()
    .toLowerCase()
    .replace(/-(outline|sharp)$/, '')
  return ION_TO_LUCIDE[base] || null
}

/** <IonIcon name="people-outline" className="h-5 w-5" /> — the lucide stand-in, or null. */
export const IonIcon = ({ name, ...props }) => {
  const icon = ionToLucide(name)
  return icon ? createElement(icon, props) : null
}
